const langButtons = document.querySelectorAll(".lang-button");
const langTarget = document.querySelectorAll("[data-i18n]");
const stockGrid = document.getElementById("stockGrid");
const availableOnly = document.getElementById("availableOnly");
const lastUpdated = document.getElementById("lastUpdated");

let activeLang = "en";
let stockData = [];

const setLanguage = (lang) => {
  activeLang = lang;
  langButtons.forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });
  langTarget.forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) {
      el.textContent = translations[lang][key];
    }
  });
  renderStock();
};

const statusLabel = (status) => {
  const labels = {
    en: {
      available: "Available",
      reserved: "Reserved",
      sold: "Sold",
    },
    zh: {
      available: "可购买",
      reserved: "已预订",
      sold: "已售出",
    },
  };
  return labels[activeLang][status] || status;
};

const renderStock = () => {
  const showAvailableOnly = availableOnly.checked;
  const items = stockData.filter((item) => !showAvailableOnly || item.status === "available");
  stockGrid.innerHTML = "";

  if (!items.length) {
    const empty = document.createElement("div");
    empty.className = "stock-card";
    empty.textContent =
      activeLang === "zh" ? "目前暂无可购买的龙猫。" : "No chinchillas are available right now.";
    stockGrid.appendChild(empty);
    return;
  }

  items.forEach((item) => {
    const card = document.createElement("article");
    card.className = "stock-card";

    const image = document.createElement("img");
    image.src = item.image;
    image.alt = activeLang === "zh" ? item.imageAltZh : item.imageAlt;
    image.loading = "lazy";

    const badge = document.createElement("span");
    badge.className = `badge ${item.status}`;
    badge.textContent = statusLabel(item.status);

    const title = document.createElement("h3");
    title.textContent = activeLang === "zh" ? item.nameZh : item.name;

    const meta = document.createElement("p");
    meta.className = "muted";
    meta.textContent = activeLang === "zh" ? item.metaZh : item.meta;

    const price = document.createElement("strong");
    price.textContent = activeLang === "zh" ? item.priceZh : item.price;

    const note = document.createElement("p");
    note.className = "muted";
    note.textContent = activeLang === "zh" ? item.noteZh : item.note;

    card.append(image, badge, title, meta, price, note);
    stockGrid.appendChild(card);
  });
};

const loadStock = async () => {
  try {
    const response = await fetch("data/stock.json");
    const data = await response.json();
    stockData = data.items;
    lastUpdated.textContent =
      activeLang === "zh"
        ? `更新：${data.lastUpdated}`
        : `Last updated: ${data.lastUpdated}`;
    renderStock();
  } catch (error) {
    stockGrid.innerHTML =
      activeLang === "zh" ? "加载失败，请稍后再试。" : "Unable to load stock right now.";
  }
};

langButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

availableOnly.addEventListener("change", renderStock);

setLanguage("en");
loadStock();
